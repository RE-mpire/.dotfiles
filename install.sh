#!/usr/bin/env bash
# Link this dotfiles repo into $HOME with GNU Stow.
#
# .stow-local-ignore is generated from:
#   stow-ignore.base   shared by every machine
#   stow-ignore.local  this machine only
#
# Extra arguments are passed to stow, e.g. ./install.sh -v

set -euo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
BASE="$REPO/stow-ignore.base"
LOCAL="$REPO/stow-ignore.local"
OUT="$REPO/.stow-local-ignore"

# Create example stow-ignore.local file
if [ ! -f "$LOCAL" ]; then
  cat > "$LOCAL" <<'EOF'
# Machine-specific stow ignores
# One Perl regex per line; ^/ anchors to the top of the repo
# Examples:
#   ^/\.bashrc
#   ^/\.config/nvim
EOF
  echo "Created $LOCAL"
fi

write_ignore() {
  {
    echo "# GENERATED by install.sh. Edit stow-ignore.base or stow-ignore.local"
    cat "$BASE"
    if [ "$1" = full ]; then
      echo
      cat "$LOCAL"
    fi
  } > "$OUT"
}

run_stow() {
  stow --no-folding --dir="$REPO" --target="$HOME" "$@" .
}

fail() {
  write_ignore full
  echo "install.sh: stow stopped (see above). Nothing was overwritten." >&2
  echo "Move or delete any real file listed as a conflict, then rerun." >&2
  exit 1
}

# Step 1: un-stow to remove symlinks that point into this repo
write_ignore base
run_stow -D "$@" || fail

# Step 2: re-stow ignoring files in base + local
write_ignore full
run_stow "$@" || fail